#!/bin/sh
# Render the Homebrew formula of a wats release.
#
#   sh scripts/homebrew-formula.sh VERSION DIR > wats.rb
#
# DIR holds the release's checksum files, wats-VERSION-<target>.tar.gz.sha256,
# already verified against the release key (the release workflow checks
# their minisign signatures before calling this). The formula pins the
# archives of the release by URL and SHA-256: macOS on Apple silicon, and
# Linux on x86_64 and arm64, the prebuilt targets.

set -eu

die() { printf 'homebrew-formula.sh: %s\n' "$*" >&2; exit 1; }

[ $# -eq 2 ] || die "usage: sh scripts/homebrew-formula.sh VERSION DIR"
VERSION="$1"
DIR="$2"
case "$VERSION" in
    [0-9]*.[0-9]*.[0-9]*) ;;
    *) die "VERSION must look like X.Y.Z, got $VERSION" ;;
esac

BASE="https://github.com/wearetheswarm/wats/releases/download/v$VERSION"

# sha TARGET: the SHA-256 of that target's archive, from its .sha256 file,
# which must name the archive.
sha() {
    archive="wats-$VERSION-$1.tar.gz"
    file="$DIR/$archive.sha256"
    [ -f "$file" ] || die "missing $file"
    sum="$(cut -d ' ' -f 1 < "$file" | tr 'A-F' 'a-f')"
    named="$(sed -n '1s/^[0-9a-fA-F]* [ *]*//p' < "$file")"
    [ "$named" = "$archive" ] || die "$file is the checksum of another file ($named)"
    printf '%s' "$sum" | grep -Eq '^[0-9a-f]{64}$' || die "$file has no SHA-256"
    printf '%s' "$sum"
}

MAC="$(sha aarch64-apple-darwin)"
LINUX="$(sha x86_64-unknown-linux-musl)"
LINUX_ARM="$(sha aarch64-unknown-linux-musl)"

cat <<FORMULA
# Generated by scripts/homebrew-formula.sh in wearetheswarm/wats for each
# release. Do not edit by hand: the next release overwrites it.
class Wats < Formula
  desc "Distributed, secure collective of AI agents thinking and acting together"
  homepage "https://github.com/wearetheswarm/wats"
  version "$VERSION"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$BASE/wats-$VERSION-aarch64-apple-darwin.tar.gz"
      sha256 "$MAC"
    end
  end

  on_linux do
    on_intel do
      url "$BASE/wats-$VERSION-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$LINUX"
    end
    on_arm do
      url "$BASE/wats-$VERSION-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$LINUX_ARM"
    end
  end

  def install
    bin.install "wats"
  end

  def caveats
    <<~EOS
      Upgrade with \`brew upgrade wats\` rather than \`wats upgrade\`, so that
      Homebrew keeps track of the installed version.
      Next: \`wats setup\`.
    EOS
  end

  test do
    assert_match "wats #{version}", shell_output("#{bin}/wats --version")
  end
end
FORMULA
